-- =============================================================================
-- 2026-11-12  Phase 2: inventory_submission_counts
-- =============================================================================
-- RUN THIS BY HAND against the app's database, BEFORE deploying the phase 2 code.
-- Nothing in the app runs it for you. The phase 1 table (inventory_count_entries)
-- must already exist.
--
-- What it does
--   1. Creates ONE new table, inventory_submission_counts: what each inventory
--      counted per product (base units). Order sheet inventories keep their
--      par / order / vendor snapshot there, so a later recount the same day
--      can no longer disturb what a purchase order shows.
--   2. Copies the existing counts into it, and gives order sheet inventories
--      their lines (units as counted) from the order sheet.
--   3. Repairs counts that the old one-row-per-day save wrote onto another
--      inventory's row (for example a manual count saved after an order sheet).
--   4. Re-picks the day's count (inventory_counts): latest submitted inventory
--      wins, product by product.
--
-- What it does NOT do
--   - It does not change any existing table's columns or rules.
--   - It does not delete anything.
--   - inventory_counts stays exactly one row per location / product / date.
--
-- The code that is live today keeps working after this runs.
-- Safe to run more than once: a second run only picks up what is new.
-- Run it once more after the phase 2 code is live, to pick up anything that was
-- saved between this run and the deploy.
--
-- The last result it shows is a small table of how many rows each step touched.
-- =============================================================================

BEGIN;

CREATE TEMP TABLE _p2_report (step_no int, step text, rows_touched bigint) ON COMMIT DROP;

-- ── 1. The table ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.inventory_submission_counts (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_submission_id  integer NOT NULL
        REFERENCES public.inventory_submissions(id) ON DELETE CASCADE,
    product_id               bigint  NOT NULL REFERENCES public.products(id),
    base_quantity            numeric(12,4),
    base_unit_id             integer REFERENCES public.units(id),
    entered_quantity         numeric(12,4),
    entered_unit_id          integer REFERENCES public.units(id),
    entered_by               varchar(256),
    vendor_item_id           integer REFERENCES public.vendor_items(id),
    vendor_id                integer REFERENCES public.vendors(id),
    vendor_code              varchar(128),
    par_qty                  numeric(12,4),
    par_unit_id              integer REFERENCES public.units(id),
    par_base_qty             numeric(12,4),
    order_qty                numeric(12,4),
    order_unit_id            integer REFERENCES public.units(id),
    original_quantity        numeric(12,4),
    corrected_by             varchar(256),
    corrected_at             timestamptz,
    correction_notes         text,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT inventory_submission_counts_unique UNIQUE (inventory_submission_id, product_id)
);

COMMENT ON TABLE public.inventory_submission_counts IS
    'What ONE inventory counted per product, in base units. Order sheet inventories keep '
    'their par / order / vendor snapshot here. inventory_counts (the day''s count) is always '
    'a copy of the row from the latest submitted inventory for that location / product / date.';

CREATE INDEX IF NOT EXISTS idx_inv_submission_counts_product
    ON public.inventory_submission_counts (product_id);

COMMENT ON TABLE public.inventory_counts IS
    'THE DAY''S COUNT: one row per location / product / date, in base units. Always a copy of '
    'the row in inventory_submission_counts from the latest SUBMITTED inventory that counted '
    'the product. Usage is calculated from this table.';

-- ── 2. Existing counts -> the inventory that holds them ──────────────────────
WITH ins AS (
    INSERT INTO public.inventory_submission_counts (
        inventory_submission_id, product_id,
        base_quantity, base_unit_id, entered_quantity, entered_unit_id, entered_by,
        vendor_item_id, vendor_id, vendor_code,
        par_qty, par_unit_id, par_base_qty, order_qty, order_unit_id,
        original_quantity, corrected_by, corrected_at, correction_notes, created_at
    )
    SELECT ic.inventory_submission_id, ic.product_id,
           ic.base_quantity, ic.base_unit_id, ic.entered_quantity, ic.entered_unit_id, ic.entered_by,
           ic.vendor_item_id, ic.vendor_id, ic.vendor_code,
           ic.par_qty, ic.par_unit_id, ic.par_base_qty, ic.order_qty, ic.order_unit_id,
           ic.original_quantity, ic.corrected_by, ic.corrected_at, ic.correction_notes, ic.created_at
    FROM public.inventory_counts ic
    WHERE ic.inventory_submission_id IS NOT NULL
    ORDER BY ic.id
    ON CONFLICT (inventory_submission_id, product_id) DO NOTHING
    RETURNING 1
)
INSERT INTO _p2_report SELECT 2, 'existing counts copied to their inventory', count(*) FROM ins;

-- ── 3. Order sheet inventories get their lines (units as counted) ────────────
-- Only for inventories that have no lines at all yet.
WITH ins AS (
    INSERT INTO public.inventory_count_entries (
        inventory_submission_id, product_id, unit_id,
        quantity, base_quantity, base_unit_id, entered_by, entered_at
    )
    SELECT ivs.id, se.product_id, se.unit_id,
           se.quantity, se.base_quantity, se.base_unit_id,
           ivs.submitted_by, COALESCE(ivs.submitted_at, ivs.created_at)
    FROM public.inventory_submissions ivs
    JOIN public.sheet_entries se ON se.submission_id = ivs.sheet_submission_id
    WHERE ivs.source = 'count_sheet'
      AND se.unit_id       IS NOT NULL
      AND se.quantity      IS NOT NULL AND se.quantity >= 0
      AND se.base_quantity IS NOT NULL
      AND se.base_unit_id  IS NOT NULL
      AND EXISTS (SELECT 1 FROM public.inventory_submission_counts c
                  WHERE c.inventory_submission_id = ivs.id AND c.product_id = se.product_id)
      AND NOT EXISTS (SELECT 1 FROM public.inventory_count_entries e
                      WHERE e.inventory_submission_id = ivs.id)
    RETURNING 1
)
INSERT INTO _p2_report SELECT 3, 'order sheet lines copied onto their inventory', count(*) FROM ins;

-- Any count that still has no line (its order sheet is gone, or it predates the
-- lines table) gets one line saying what the count row says.
WITH ins AS (
    INSERT INTO public.inventory_count_entries (
        inventory_submission_id, product_id, unit_id,
        quantity, base_quantity, base_unit_id, entered_by, entered_at
    )
    SELECT c.inventory_submission_id, c.product_id,
           CASE WHEN c.entered_unit_id IS NOT NULL AND c.entered_quantity IS NOT NULL
                THEN c.entered_unit_id  ELSE c.base_unit_id  END,
           CASE WHEN c.entered_unit_id IS NOT NULL AND c.entered_quantity IS NOT NULL
                THEN c.entered_quantity ELSE c.base_quantity END,
           c.base_quantity, c.base_unit_id, c.entered_by, c.created_at
    FROM public.inventory_submission_counts c
    WHERE c.base_quantity IS NOT NULL AND c.base_quantity >= 0
      AND c.base_unit_id  IS NOT NULL
      AND COALESCE(c.entered_quantity, 0) >= 0
      AND NOT EXISTS (SELECT 1 FROM public.inventory_count_entries e
                      WHERE e.inventory_submission_id = c.inventory_submission_id
                        AND e.product_id = c.product_id
                        AND e.superseded_at IS NULL)
    RETURNING 1
)
INSERT INTO _p2_report SELECT 3, 'counts without lines given one line', count(*) FROM ins;

-- ── 4. Counts corrected by a manager: the lines follow the correction ────────
-- (Phase 1 corrections changed the count but not the lines.)
CREATE TEMP TABLE _p2_corrected ON COMMIT DROP AS
SELECT c.inventory_submission_id, c.product_id
FROM public.inventory_submission_counts c
JOIN LATERAL (
    SELECT ROUND(SUM(e.base_quantity), 4) AS total
    FROM public.inventory_count_entries e
    WHERE e.inventory_submission_id = c.inventory_submission_id
      AND e.product_id = c.product_id AND e.superseded_at IS NULL
) t ON TRUE
WHERE c.corrected_at IS NOT NULL
  AND c.base_quantity IS NOT NULL AND c.base_quantity >= 0
  AND c.base_unit_id  IS NOT NULL
  AND t.total IS DISTINCT FROM c.base_quantity;

UPDATE public.inventory_count_entries e
SET superseded_at = now(), superseded_by = 'phase 2 data update'
FROM _p2_corrected x
WHERE e.inventory_submission_id = x.inventory_submission_id
  AND e.product_id = x.product_id
  AND e.superseded_at IS NULL;

WITH ins AS (
    INSERT INTO public.inventory_count_entries (
        inventory_submission_id, product_id, unit_id,
        quantity, base_quantity, base_unit_id, entered_by, entered_at
    )
    SELECT c.inventory_submission_id, c.product_id,
           CASE WHEN c.entered_unit_id IS NOT NULL AND c.entered_quantity >= 0
                THEN c.entered_unit_id  ELSE c.base_unit_id  END,
           CASE WHEN c.entered_unit_id IS NOT NULL AND c.entered_quantity >= 0
                THEN c.entered_quantity ELSE c.base_quantity END,
           c.base_quantity, c.base_unit_id, c.corrected_by, c.corrected_at
    FROM public.inventory_submission_counts c
    JOIN _p2_corrected x
      ON x.inventory_submission_id = c.inventory_submission_id AND x.product_id = c.product_id
    RETURNING 1
)
INSERT INTO _p2_report SELECT 4, 'corrected counts: lines brought in step', count(*) FROM ins;

-- ── 5. Repair counts that another inventory's save overwrote ─────────────────
-- Until now there was one row per product per day, so a manual save landed on
-- whichever inventory created that row first. An inventory's own lines say what
-- it really counted; put that number back.
--   manual inventory:      its lines are what was typed into it.
--   order sheet inventory: only when the row carries a typed unit, which only a
--                          manual save writes there. Its lines are the order
--                          sheet's own on-hand lines (step 3).
-- Counts a manager corrected are left alone (step 4 handled them).
WITH fix AS (
    UPDATE public.inventory_submission_counts c
    SET base_quantity    = t.total,
        base_unit_id     = t.base_unit_id,
        entered_quantity = CASE WHEN ivs.source = 'count_sheet' THEN NULL
                                WHEN t.line_count = 1 THEN t.one_quantity ELSE t.total END,
        entered_unit_id  = CASE WHEN ivs.source = 'count_sheet' THEN NULL
                                WHEN t.line_count = 1 THEN t.one_unit_id ELSE t.base_unit_id END,
        entered_by       = CASE WHEN ivs.source = 'count_sheet' THEN ivs.submitted_by
                                ELSE COALESCE(t.entered_by, c.entered_by) END,
        updated_at       = now()
    FROM public.inventory_submissions ivs,
         (
            SELECT e.inventory_submission_id, e.product_id,
                   ROUND(SUM(e.base_quantity), 4) AS total,
                   MAX(e.base_unit_id) AS base_unit_id,
                   COUNT(*)            AS line_count,
                   MAX(e.quantity)     AS one_quantity,
                   MAX(e.unit_id)      AS one_unit_id,
                   (ARRAY_AGG(e.entered_by ORDER BY e.entered_at DESC, e.id DESC))[1] AS entered_by
            FROM public.inventory_count_entries e
            WHERE e.superseded_at IS NULL
            GROUP BY e.inventory_submission_id, e.product_id
         ) t
    WHERE ivs.id = c.inventory_submission_id
      AND t.inventory_submission_id = c.inventory_submission_id
      AND t.product_id = c.product_id
      AND c.corrected_at IS NULL
      AND t.total IS DISTINCT FROM c.base_quantity
      AND (ivs.source = 'manual'
           OR (ivs.source = 'count_sheet' AND c.entered_unit_id IS NOT NULL))
    RETURNING 1
)
INSERT INTO _p2_report SELECT 5, 'overwritten counts put back', count(*) FROM fix;

-- ── 6. Submitted manual inventories get their own product totals ─────────────
-- (the ones whose save landed on another inventory's row and so have none)
WITH ins AS (
    INSERT INTO public.inventory_submission_counts (
        inventory_submission_id, product_id,
        base_quantity, base_unit_id, entered_quantity, entered_unit_id, entered_by, created_at
    )
    SELECT t.inventory_submission_id, t.product_id,
           t.total, t.base_unit_id,
           CASE WHEN t.line_count = 1 THEN t.one_quantity ELSE t.total        END,
           CASE WHEN t.line_count = 1 THEN t.one_unit_id  ELSE t.base_unit_id END,
           t.entered_by, t.first_entered_at
    FROM (
        SELECT e.inventory_submission_id, e.product_id,
               SUM(e.base_quantity) AS total,
               MAX(e.base_unit_id)  AS base_unit_id,
               COUNT(*)             AS line_count,
               MAX(e.quantity)      AS one_quantity,
               MAX(e.unit_id)       AS one_unit_id,
               (ARRAY_AGG(e.entered_by ORDER BY e.entered_at DESC, e.id DESC))[1] AS entered_by,
               MIN(e.entered_at)    AS first_entered_at
        FROM public.inventory_count_entries e
        JOIN public.inventory_submissions ivs ON ivs.id = e.inventory_submission_id
        WHERE e.superseded_at IS NULL
          AND ivs.source = 'manual' AND ivs.status = 'submitted'
        GROUP BY e.inventory_submission_id, e.product_id
    ) t
    ON CONFLICT (inventory_submission_id, product_id) DO NOTHING
    RETURNING 1
)
INSERT INTO _p2_report SELECT 6, 'manual inventories given their own totals', count(*) FROM ins;

-- ── 7. The day's count: latest submitted inventory wins, per product ─────────
WITH winners AS (
    SELECT DISTINCT ON (ivs.location_id, ivs.count_date, c.product_id)
           c.*, ivs.location_id, ivs.count_date, ivs.sheet_submission_id
    FROM public.inventory_submission_counts c
    JOIN public.inventory_submissions ivs ON ivs.id = c.inventory_submission_id
    WHERE ivs.status = 'submitted'
    ORDER BY ivs.location_id, ivs.count_date, c.product_id,
             ivs.submitted_at DESC NULLS LAST, ivs.id DESC
),
up AS (
    INSERT INTO public.inventory_counts (
        inventory_submission_id, submission_id, location_id, product_id, count_date,
        base_quantity, base_unit_id, entered_quantity, entered_unit_id, entered_by,
        vendor_item_id, vendor_id, vendor_code,
        par_qty, par_unit_id, par_base_qty, order_qty, order_unit_id,
        original_quantity, corrected_by, corrected_at, correction_notes
    )
    SELECT w.inventory_submission_id, w.sheet_submission_id, w.location_id, w.product_id, w.count_date,
           w.base_quantity, w.base_unit_id, w.entered_quantity, w.entered_unit_id, w.entered_by,
           w.vendor_item_id, w.vendor_id, w.vendor_code,
           w.par_qty, w.par_unit_id, w.par_base_qty, w.order_qty, w.order_unit_id,
           w.original_quantity, w.corrected_by, w.corrected_at, w.correction_notes
    FROM winners w
    ON CONFLICT (location_id, product_id, count_date) DO UPDATE SET
        inventory_submission_id = EXCLUDED.inventory_submission_id,
        submission_id           = EXCLUDED.submission_id,
        base_quantity           = EXCLUDED.base_quantity,
        base_unit_id            = EXCLUDED.base_unit_id,
        entered_quantity        = EXCLUDED.entered_quantity,
        entered_unit_id         = EXCLUDED.entered_unit_id,
        entered_by              = EXCLUDED.entered_by,
        vendor_item_id          = EXCLUDED.vendor_item_id,
        vendor_id               = EXCLUDED.vendor_id,
        vendor_code             = EXCLUDED.vendor_code,
        par_qty                 = EXCLUDED.par_qty,
        par_unit_id             = EXCLUDED.par_unit_id,
        par_base_qty            = EXCLUDED.par_base_qty,
        order_qty               = EXCLUDED.order_qty,
        order_unit_id           = EXCLUDED.order_unit_id,
        original_quantity       = EXCLUDED.original_quantity,
        corrected_by            = EXCLUDED.corrected_by,
        corrected_at            = EXCLUDED.corrected_at,
        correction_notes        = EXCLUDED.correction_notes
    WHERE (inventory_counts.inventory_submission_id, inventory_counts.base_quantity,
           inventory_counts.base_unit_id, inventory_counts.entered_quantity,
           inventory_counts.entered_unit_id)
          IS DISTINCT FROM
          (EXCLUDED.inventory_submission_id, EXCLUDED.base_quantity,
           EXCLUDED.base_unit_id, EXCLUDED.entered_quantity,
           EXCLUDED.entered_unit_id)
    RETURNING 1
)
INSERT INTO _p2_report SELECT 7, 'day''s counts set to the latest submitted inventory', count(*) FROM up;

-- ── Things left exactly as they were, for you to look at (nothing is changed) ─
INSERT INTO _p2_report
SELECT 8, 'left alone: day''s counts whose inventory was deleted earlier', count(*)
FROM public.inventory_counts WHERE inventory_submission_id IS NULL;

INSERT INTO _p2_report
SELECT 8, 'left alone: day''s counts written by an inventory that is still a draft', count(*)
FROM public.inventory_counts ic
JOIN public.inventory_submissions ivs ON ivs.id = ic.inventory_submission_id
WHERE ivs.status = 'draft';

SELECT step_no AS step, step AS what, rows_touched AS rows FROM _p2_report ORDER BY step_no, step;

COMMIT;
