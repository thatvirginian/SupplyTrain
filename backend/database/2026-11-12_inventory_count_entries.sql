-- =============================================================================
-- 2026-11-12  inventory_count_entries
-- =============================================================================
-- Every line an inventory saved, exactly as entered (e.g. "2 case" and "5 each"),
-- plus the base-unit amount each line converted to.
--
--   inventory_counts         = the day's figure per product (base units, one row)
--   inventory_count_entries  = the lines behind it, per inventory
--
-- History: a changed line is never updated in place. The old row gets
-- superseded_at / superseded_by and a new row is inserted. Current lines are
-- the rows with superseded_at IS NULL.
--
-- Safe to run more than once. Run as the app's DB owner:
--   psql "$DATABASE_URL" -f backend/database/migrations/2026-11-12_inventory_count_entries.sql
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.inventory_count_entries (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_submission_id  integer NOT NULL
        REFERENCES public.inventory_submissions(id) ON DELETE CASCADE,
    product_id               bigint  NOT NULL REFERENCES public.products(id),
    unit_id                  integer NOT NULL REFERENCES public.units(id),
    quantity                 numeric(12,4) NOT NULL CHECK (quantity >= 0),
    base_quantity            numeric(14,6) NOT NULL,
    base_unit_id             integer NOT NULL REFERENCES public.units(id),
    entered_by               varchar(256),
    entered_at               timestamptz NOT NULL DEFAULT now(),
    superseded_at            timestamptz,
    superseded_by            varchar(256)
);

COMMENT ON TABLE public.inventory_count_entries IS
    'Lines saved by each inventory, as entered (quantity + unit) and converted to base. '
    'Rows are never edited: a change supersedes the old row and inserts a new one. '
    'Current lines: superseded_at IS NULL.';

-- One current line per inventory / product / unit.
CREATE UNIQUE INDEX IF NOT EXISTS idx_inv_count_entries_current
    ON public.inventory_count_entries (inventory_submission_id, product_id, unit_id)
    WHERE superseded_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_inv_count_entries_product
    ON public.inventory_count_entries (product_id);

-- Backfill: one current line per existing manual count that recorded what was typed.
-- (Order-sheet inventories keep their lines in sheet_entries; phase 2 links those.)
INSERT INTO public.inventory_count_entries (
    inventory_submission_id, product_id, unit_id,
    quantity, base_quantity, base_unit_id, entered_by, entered_at
)
SELECT ic.inventory_submission_id, ic.product_id, ic.entered_unit_id,
       ic.entered_quantity, ic.base_quantity, ic.base_unit_id,
       ic.entered_by, ic.created_at
FROM public.inventory_counts ic
JOIN public.inventory_submissions ivs ON ivs.id = ic.inventory_submission_id
WHERE ivs.source = 'manual'
  AND ic.entered_quantity IS NOT NULL
  AND ic.entered_unit_id  IS NOT NULL
  AND ic.base_quantity    IS NOT NULL
  AND ic.base_unit_id     IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM public.inventory_count_entries e
      WHERE e.inventory_submission_id = ic.inventory_submission_id
        AND e.product_id = ic.product_id
  );

COMMIT;
