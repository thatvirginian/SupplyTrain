-- =============================================================================
-- 2026-11-16  Transfers (store to store) and Unscheduled Orders (from a vendor)
-- =============================================================================
-- RUN THIS BY HAND against the app's database, BEFORE deploying the code that
-- goes with it. Nothing in the app runs it for you.
--
-- Why
--   Two kinds of movement happen outside the order sheet, and neither one
--   touches inventory:
--     * TRANSFER: one store sends product to another store (ran out of
--       tortillas, borrow from the store down the road).
--     * UNSCHEDULED ORDER: an order placed with a vendor (usually the
--       commissary) that is not driven by a count, e.g. a catering.
--
-- What it does
--   1. purchase_orders gets three columns:
--        order_type  'scheduled' (made by an order sheet, every existing row)
--                    or 'unscheduled' (made by hand, no inventory behind it)
--        reason      catering / event / special / other   (unscheduled only)
--        reference   free text: catering number, customer, event name
--      Unscheduled orders are ordinary purchase orders after that: same
--      lifecycle (open -> accepted -> shipped -> fulfilled), same Order
--      History, same commissary pick list and PDF.
--   2. Fixes the purchase_orders.status default. It was 'draft', which its own
--      CHECK constraint rejects. Every insert in the app sets status
--      explicitly, so nothing changes for existing code.
--   3. New tables transfers and transfer_items.
--      Transfer lifecycle: open -> sent -> received   (or cancelled)
--
-- What it does NOT do
--   - It changes no existing row except setting order_type = 'scheduled'
--     (the column default) on existing purchase orders.
--   - It deletes nothing.
--
-- The code that is live today keeps working after this runs.
-- Safe to run more than once.
-- =============================================================================

BEGIN;

-- ── 1. Unscheduled orders live in purchase_orders ───────────────────────────

ALTER TABLE public.purchase_orders
    ADD COLUMN IF NOT EXISTS order_type character varying(16) DEFAULT 'scheduled' NOT NULL,
    ADD COLUMN IF NOT EXISTS reason     character varying(32),
    ADD COLUMN IF NOT EXISTS reference  character varying(256);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'purchase_orders_order_type_check') THEN
        ALTER TABLE public.purchase_orders
            ADD CONSTRAINT purchase_orders_order_type_check
            CHECK ((order_type)::text = ANY (ARRAY['scheduled','unscheduled']::text[]));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'purchase_orders_reason_check') THEN
        ALTER TABLE public.purchase_orders
            ADD CONSTRAINT purchase_orders_reason_check
            CHECK (reason IS NULL OR (reason)::text = ANY (ARRAY['catering','event','special','other']::text[]));
    END IF;
END $$;

COMMENT ON COLUMN public.purchase_orders.order_type IS
    'scheduled = made by an order sheet (has an inventory behind it). unscheduled = placed by hand (catering etc.), no inventory, par or on hand.';
COMMENT ON COLUMN public.purchase_orders.reason IS
    'Why an unscheduled order was placed: catering, event, special, other. NULL for scheduled orders.';
COMMENT ON COLUMN public.purchase_orders.reference IS
    'Free text for unscheduled orders: catering order number, customer or event name.';

ALTER TABLE public.purchase_orders ALTER COLUMN status SET DEFAULT 'open';

CREATE INDEX IF NOT EXISTS idx_purchase_orders_order_type
    ON public.purchase_orders USING btree (order_type);


-- ── 2. Transfers ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.transfers (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_location_id  character varying(64) NOT NULL,
    to_location_id    character varying(64) NOT NULL,
    transfer_date     date DEFAULT CURRENT_DATE NOT NULL,
    status            character varying(16) DEFAULT 'open' NOT NULL,
    reason            character varying(32),
    notes             text,
    created_by        character varying(256),
    created_at        timestamp with time zone DEFAULT now() NOT NULL,
    updated_at        timestamp with time zone DEFAULT now() NOT NULL,
    sent_at           timestamp with time zone,
    sent_by           character varying(256),
    received_at       timestamp with time zone,
    received_by       character varying(256),
    received_note     text,
    cancelled_at      timestamp with time zone,
    cancelled_by      character varying(256),
    CONSTRAINT transfers_status_check
        CHECK ((status)::text = ANY (ARRAY['open','sent','received','cancelled']::text[])),
    CONSTRAINT transfers_reason_check
        CHECK (reason IS NULL OR (reason)::text = ANY (ARRAY['shortage','catering','event','overstock','other']::text[])),
    CONSTRAINT transfers_different_locations
        CHECK (from_location_id <> to_location_id)
);

COMMENT ON TABLE public.transfers IS
    'Product sent from one store to another. Not tied to inventory or purchase orders. open (editable) -> sent (locked, on its way) -> received (to-store confirmed); cancelled at any point before received.';
COMMENT ON COLUMN public.transfers.from_location_id IS 'Sending store (locations.store_guid as text).';
COMMENT ON COLUMN public.transfers.to_location_id   IS 'Receiving store (locations.store_guid as text).';

CREATE TABLE IF NOT EXISTS public.transfer_items (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id        integer NOT NULL REFERENCES public.transfers(id) ON DELETE CASCADE,
    product_id         bigint  NOT NULL REFERENCES public.products(id),
    product_name       character varying(256) NOT NULL,
    quantity           numeric(12,4) NOT NULL,
    unit_id            integer NOT NULL REFERENCES public.units(id),
    base_quantity      numeric(12,4),
    base_unit_id       integer REFERENCES public.units(id),
    received_quantity  numeric(12,4),
    received_note      text,
    notes              text,
    sort_order         integer DEFAULT 0 NOT NULL,
    created_at         timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT transfer_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT transfer_items_unique UNIQUE (transfer_id, product_id)
);

COMMENT ON TABLE public.transfer_items IS
    'Lines of a transfer. product_name snapshotted when saved. base_quantity = quantity converted to the product base unit at save time.';
COMMENT ON COLUMN public.transfer_items.received_quantity IS
    'What the receiving store actually got, in unit_id. NULL until received (then defaults to quantity).';

CREATE INDEX IF NOT EXISTS idx_transfers_from_location ON public.transfers USING btree (from_location_id, transfer_date);
CREATE INDEX IF NOT EXISTS idx_transfers_to_location   ON public.transfers USING btree (to_location_id, transfer_date);
CREATE INDEX IF NOT EXISTS idx_transfers_status        ON public.transfers USING btree (status);
CREATE INDEX IF NOT EXISTS idx_transfer_items_transfer ON public.transfer_items USING btree (transfer_id);
CREATE INDEX IF NOT EXISTS idx_transfer_items_product  ON public.transfer_items USING btree (product_id);

COMMIT;

